const languageButton = document.querySelector(".language-toggle");
const menuButton = document.querySelector(".menu-toggle");
const menu = document.querySelector(".site-nav");
const cvLinks = document.querySelectorAll("[data-cv-link]");
const richTextKeys = new Set(["heroLead", "auraSummary", "aboutIntro", "contactTitle"]);
let language = "vi";

function setLanguage(next) {
  language = next === "en" ? "en" : "vi";
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (!(key in translations[language])) return;
    if (richTextKeys.has(key)) node.innerHTML = translations[language][key];
    else node.textContent = translations[language][key];
  });
  document.querySelector(".lang-vi").classList.toggle("active", language === "vi");
  document.querySelector(".lang-en").classList.toggle("active", language === "en");
  languageButton.setAttribute("aria-label", language === "vi" ? "Switch to English" : "Chuyển sang tiếng Việt");
  menuButton.setAttribute("aria-label", language === "vi" ? "Mở menu" : "Open menu");
  document.querySelector(".skip-link").textContent = language === "vi" ? "Chuyển đến nội dung" : "Skip to content";
  document.querySelector(".footer-inner > div:first-child span").textContent = translations[language].footerLocation;
  document.querySelector('meta[name="description"]').content = language === "vi"
    ? "Portfolio Nguyễn Minh Thức — sinh viên Kỹ thuật phần mềm, định hướng Java Backend. Dự án AURA Shoe Store và Tetris 2048 Fusion."
    : "Nguyen Minh Thuc's Java Backend portfolio. Explore AURA Shoe Store, Tetris 2048 Fusion, skills, and achievements.";
  cvLinks.forEach((link) => { link.href = "assets/cv/CV_Nguyen_Minh_Thuc_" + language.toUpperCase() + ".pdf"; });
  try { localStorage.setItem("portfolio-language", language); } catch (_) {}
}

languageButton.addEventListener("click", () => setLanguage(language === "vi" ? "en" : "vi"));
menuButton.addEventListener("click", () => {
  const open = menu.classList.toggle("open");
  menuButton.setAttribute("aria-expanded", String(open));
});
menu.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => {
  menu.classList.remove("open");
  menuButton.setAttribute("aria-expanded", "false");
}));
try {
  const saved = localStorage.getItem("portfolio-language");
  if (saved === "en") setLanguage("en");
} catch (_) {}
